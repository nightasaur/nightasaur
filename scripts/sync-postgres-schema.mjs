import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const source = new URL('../apps/backend/prisma/schema.prisma', import.meta.url);
const target = new URL('../apps/backend/prisma/postgresql/schema.prisma', import.meta.url);
const input = readFileSync(source, 'utf8');
const marker = 'provider = "sqlite"';
if (input.split(marker).length !== 2) throw new Error('Expected exactly one SQLite datasource');
const expected = '// Generated by scripts/sync-postgres-schema.mjs; edit the canonical schema instead.\n' + input.replace(marker, 'provider = "postgresql"');
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== expected) throw new Error('PostgreSQL schema is stale');
} else writeFileSync(fileURLToPath(target), expected);
